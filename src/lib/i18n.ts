export type TranslationKey = keyof (typeof translations)["tg"];

const statusKeyMap: Record<string, TranslationKey> = {
  draft: "statusDraft",
  published: "statusPublished",
  receiving_offers: "statusReceivingOffers",
  master_selected: "statusMasterSelected",
  in_progress: "statusInProgress",
  completed: "statusCompleted",
  cancelled: "statusCancelled",
  pending: "statusPending",
  accepted: "statusAccepted",
  rejected: "statusRejected",
  hidden: "statusHidden",
  reviewed: "statusReviewed",
  resolved: "statusResolved",
};

const roleKeyMap: Record<string, TranslationKey> = {
  customer: "roleCustomer",
  master: "roleMaster",
  admin: "roleAdmin",
};

export function t(locale: Locale, key: TranslationKey, vars?: Record<string, string | number>) {
  let text: string = translations[locale][key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replace(`{${k}}`, String(v));
    }
  }
  return text;
}

export function statusLabel(locale: Locale, status: string) {
  const key = statusKeyMap[status];
  return key ? t(locale, key) : status;
}

export function roleLabel(locale: Locale, role: string) {
  const key = roleKeyMap[role];
  return key ? t(locale, key) : role;
}
